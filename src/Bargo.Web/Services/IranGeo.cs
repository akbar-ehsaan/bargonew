    //  نمایندهٔ اصفهان را به تهران وصل می‌کند، دومی قلمروش را **خالی** می‌کند و
    //  نماینده هیچ زیرمجموعه‌ای نمی‌بیند بی‌آنکه هیچ خطایی جایی ثبت شود.
    //
    //  ‎Areas/Admin/Controllers/ProvincesController‎ همین نرمال‌سازی را از قبل
    //  داشت ولی ‎private‎ بود و فقط صفحهٔ «پوشش استانی» از آن سود می‌برد. حالا
    //  اینجاست تا همهٔ خواننده‌ها یک تعریف داشته باشند.
    // ------------------------------------------------------------------

    /// <summary>نگاشت «کلید نرمال‌شده ← (نام رسمی، شناسهٔ یک‌مبنا)».</summary>
    private static readonly Dictionary<string, (string Name, int Id)> CanonicalProvinceByKey =
        Map.Keys.Select((k, i) => (Key: NormalizeName(k), Name: k, Id: i + 1))
                .ToDictionary(x => x.Key, x => (x.Name, x.Id), StringComparer.Ordinal);

    /// <summary>
    /// کلیدِ تطبیق نام: «ی/ک» عربی یکسان می‌شود، نیم‌فاصله و نویسه‌های جهت‌دهی به
    /// فاصله تبدیل می‌شوند و فاصله‌های پیاپی فشرده می‌شوند.
    ///
    /// چرا خودِ نویسه‌ها را در پایگاه‌داده اصلاح نمی‌کنیم: ردیف‌های موجود دست‌نخورده
    /// می‌مانند و همین تابع هر بار آن‌ها را می‌فهمد. اصلاحِ یک‌بارهٔ داده هم لازم
    /// نیست و هم ریسکِ مهاجرتی دارد که این کار به آن نیاز ندارد.
    /// </summary>
    public static string NormalizeName(string? s)
    {
        if (string.IsNullOrWhiteSpace(s)) return "";

        var sb = new System.Text.StringBuilder(s.Length);
        var pendingSpace = false;

        foreach (var raw in s)
        {
            var ch = raw switch
            {
                'ي' => 'ی',   // یای عربی
                'ك' => 'ک',   // کاف عربی
                'ۀ' => 'ه',
                'ة' => 'ه',
                '‌' or '‍' or '‎' or '‏' or '‪' or '‫'
                    or '‬' or '‭' or '‮' or 'ً' or 'ٌ' or 'ٍ'
                    or 'َ' or 'ُ' or 'ِ' or 'ّ' or 'ْ' => ' ',
                _ => raw
            };

            if (char.IsWhiteSpace(ch)) { pendingSpace = sb.Length > 0; continue; }
            if (pendingSpace) { sb.Append(' '); pendingSpace = false; }
            sb.Append(ch);
        }

        return sb.ToString();
    }

    /// <summary>
    /// نامِ رسمیِ استان از روی هر املایی — یا <c>null</c> اگر به هیچ استانی نخورَد.
    ///
    /// عمداً <c>null</c> برمی‌گرداند و نه «تهران»: در مسیرهای دسترسی، حدسِ اشتباه
    /// یعنی واگذاری استانی که هیچ‌کس نخواسته است.
    /// </summary>
    public static string? CanonicalProvince(string? name) =>
        CanonicalProvinceByKey.TryGetValue(NormalizeName(name), out var c) ? c.Name : null;

    /// <summary>شناسهٔ یک‌مبنای استان از روی هر املایی — یا <c>null</c> برای ناشناخته.</summary>
    public static int? ProvinceIdOrNull(string? name) =>
        CanonicalProvinceByKey.TryGetValue(NormalizeName(name), out var c) ? c.Id : null;

    /// <summary>
    /// نامِ رسمیِ شهر از روی هر املایی، در یک استانِ مشخص — یا <c>null</c>.
    ///
    /// برای شهر هم لازم است چون کلیدِ قلمرو «شناسهٔ استان|نامِ شهر» است و اگر
    /// ادمین شهری را با املای دیگری ذخیره کند، آن کلید با هیچ ردیفی جور درنمی‌آید
    /// و نماینده شهرِ خودش را هم نمی‌بیند.
    /// </summary>
    public static string? CanonicalCity(string? province, string? city)
    {
        var canonProv = CanonicalProvince(province);
        if (canonProv == null || string.IsNullOrWhiteSpace(city)) return null;
        var key = NormalizeName(city);
        foreach (var c in Map[canonProv])
            if (NormalizeName(c) == key) return c;
        return null;
    }

    /// <summary>
    /// نامِ شهر برای **ذخیره‌سازی**: اگر شهرِ فهرست باشد به املای رسمی، وگرنه
    /// همان‌طور که آمده (فقط trim).
    ///
    /// چرا لازم است: قلمروِ شهریِ نماینده با کلیدِ «شناسهٔ استان|نامِ شهر» کار
    /// می‌کند و آن کلید همیشه املای رسمی دارد. اگر ستون ‎City‎ یک مرکز با املای
    /// دیگری پر شده باشد — و مسیرهای API آن را بی‌هیچ اعتبارسنجی‌ای می‌نویسند —
    /// نمایندهٔ همان شهر آن مرکز را **نمی‌بیند**، بی‌آنکه هیچ خطایی جایی ثبت شود.
    /// همان خرابیِ نامِ استان، یک پله پایین‌تر.
    ///
    /// چرا نامِ بیرونِ فهرست دور ریخته نمی‌شود: فهرست شهرها هرگز کامل نیست و
    /// نباید یک ثبت‌نامِ درست را به‌خاطر نقصِ دادهٔ خودمان خالی کنیم. چنین شهری
    /// در قلمروِ شهریِ هیچ نماینده‌ای هم نمی‌تواند باشد (کشوی ادمین فقط شهرهای
    /// همین فهرست را می‌دهد)، پس نگه‌داشتنش هیچ مرزی را جابه‌جا نمی‌کند.
    /// </summary>
    public static string NormalizeCity(string? province, string? city) =>
        CanonicalCity(province, city) ?? (city ?? "").Trim();

    /// <summary>حداکثر طول نامِ شهرِ دست‌نویس؛ ستون City در پایگاه‌داده رشتهٔ کوتاه است.</summary>
    private const int MaxCityLength = 60;

    /// <summary>
    /// شهر نهایی از روی آنچه فرم فرستاده است.
    ///
    /// سه حالت دارد و هر سه عمدی‌اند:
    ///  • شهرِ فهرست ⇒ همان نام (پس از trim) برگردانده می‌شود.
    ///  • <see cref="OtherCity"/> ⇒ متنِ دست‌نویسِ کاربر، اگر خالی نباشد.
    ///  • هر چیز دیگر (استانِ ناهمخوان، مقدار جعلی، خالی) ⇒ null، یعنی «نامعتبر».
    ///
    /// چرا اعتبارسنجی سمت سرور: کشوی آبشاری فقط در مرورگر است و هر کسی می‌تواند
    /// درخواست POST دستی بفرستد. بدون این تابع، «شهرِ زیرِ استان» صرفاً یک قرارداد
    /// نمایشی می‌ماند و دادهٔ پایگاه‌داده دوباره به‌هم می‌ریزد.
    /// </summary>
    public static string? Resolve(string? province, string? city, string? otherCity)
    {
        var c = (city ?? "").Trim();

        if (string.Equals(c, OtherCity, StringComparison.Ordinal))
        {
            var free = (otherCity ?? "").Trim();
            if (free.Length == 0) return null;
            return free.Length > MaxCityLength ? free[..MaxCityLength] : free;
        }

        return IsValidPair(province, c) ? c : null;
    }
