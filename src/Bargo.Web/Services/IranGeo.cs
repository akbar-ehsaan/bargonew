        !string.IsNullOrWhiteSpace(province) && Map.TryGetValue(province.Trim(), out var c)
            ? c : [];

    /// <summary>آیا این شهر واقعاً در این استان هست؟ برای اعتبارسنجی سمت سرور.</summary>
    public static bool IsValidPair(string? province, string? city)
    {
        if (string.IsNullOrWhiteSpace(city)) return false;
        var list = Cities(province);
        return list.Contains(city.Trim(), StringComparer.Ordinal);
    }

